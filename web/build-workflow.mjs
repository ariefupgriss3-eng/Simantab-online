import fs from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
await import('./build-kadis.mjs');
const path='.vercel/output/static/index.html';
let html=await fs.readFile(path,'utf8');
const url='https://raw.githubusercontent.com/ariefupgriss3-eng/Simantab-online/main/web/team-workflow-authority.js';
const r=await fetch(url,{headers:{'user-agent':'SIMANTAB-Workflow-Build/1.0'},cache:'no-store'});
if(!r.ok)throw new Error(`Gagal mengambil workflow module: ${r.status}`);
const code=await r.text();
if(!code.includes('SIMANTAB_TEAM_WORKFLOW_AUTHORITY_V1'))throw new Error('Marker workflow authority tidak ditemukan.');
const tmp='/tmp/team-workflow-authority.mjs';await fs.writeFile(tmp,code);const check=spawnSync(process.execPath,['--check',tmp],{encoding:'utf8'});if(check.status!==0)throw new Error(`Syntax workflow gagal: ${(check.stderr||check.stdout||'').trim()}`);
html=html.replaceAll("STAFF_KP_EKIN:'Staf KP & E-Kin'","STAFF_KP_EKIN:'Staf KP/PAK/Jabfung/SKP-PAK'");
html=html.replaceAll("STAFF_ARSIP:'Staf Arsip'","STAFF_ARSIP:'Staf Arsip & Aset'");
html=html.replaceAll("STAFF_CUTI:'Staf Izin Cuti'","STAFF_CUTI:'Staf Izin Cuti/Sakit/Umroh'");
html=html.replaceAll("STAFF_SPJ_SIMTENDIK:'Staf SPJ & Simtendik'","STAFF_SPJ_SIMTENDIK:'Staf Simtendik'");
html=html.replace(/<script\s+type=["']module["']\s+src=["']\.\/team-workflow-authority\.js(?:\?v=\d+)?["']><\/script>\s*/gi,'');
const body=html.lastIndexOf('</body>');if(body<0)throw new Error('Body penutup tidak ditemukan.');
html=html.slice(0,body)+'<script type="module" src="./team-workflow-authority.js?v=1"></script>\n'+html.slice(body);
await fs.writeFile(path,html);await fs.writeFile('.vercel/output/static/team-workflow-authority.js',code);
console.log(JSON.stringify({ok:true,workflowAuthority:true,serviceRouting:'Kabid > Kasi/Subkoor per jenjang > staf layanan',discipline:['PEMBINAAN_DISIPLIN','PERCERAIAN'],activityPIC:['KASI_SD','KASI_SMP','SUBKOOR_TK']}));
