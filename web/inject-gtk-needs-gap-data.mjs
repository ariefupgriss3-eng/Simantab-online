import fs from 'node:fs/promises';
import path from 'node:path';

const outputPath='.vercel/output/static/index.html';
const staticDir='.vercel/output/static';
const file='gtk-needs-gap-data.js';
const reviewFile='gtk-needs-review-v7.js';
const finalFile='gtk-needs-table-final.js';
const code=await fs.readFile(new URL(`./${file}`,import.meta.url),'utf8');
const reviewCode=await fs.readFile(new URL(`./${reviewFile}`,import.meta.url),'utf8');
const finalCode=await fs.readFile(new URL(`./${finalFile}`,import.meta.url),'utf8');
if(!/SIMANTAB_GTK_NEEDS_GAP_DATA_V6/.test(code))throw new Error('GTK needs Gap Data v6 tidak valid.');
if(!/SIMANTAB_GTK_NEEDS_REVIEW_V7/.test(reviewCode))throw new Error('GTK needs review v7 tidak valid.');
if(!/SIMANTAB_GTK_NEEDS_TABLE_FINAL_V8/.test(finalCode))throw new Error('GTK needs table final v8 tidak valid.');
await fs.writeFile(path.join(staticDir,file),code);
await fs.writeFile(path.join(staticDir,reviewFile),reviewCode);
await fs.writeFile(path.join(staticDir,finalFile),finalCode);
let html=await fs.readFile(outputPath,'utf8');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/gtk-needs-gap-data\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/gtk-needs-review-v7\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/gtk-needs-table-final\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
const close=html.lastIndexOf('</body>');
if(close<0)throw new Error('Tag </body> tidak ditemukan saat inject Gap Data.');
const tags='<script type="module" src="./gtk-needs-gap-data.js?v=6"></script>\n<script type="module" src="./gtk-needs-review-v7.js?v=1"></script>\n<script type="module" src="./gtk-needs-table-final.js?v=8"></script>\n';
html=html.slice(0,close)+tags+html.slice(close);
if(html.split('./gtk-needs-gap-data.js?v=6').length-1!==1)throw new Error('Referensi Gap Data v6 harus tepat satu kali.');
if(html.split('./gtk-needs-review-v7.js?v=1').length-1!==1)throw new Error('Referensi review v7 harus tepat satu kali.');
if(html.split('./gtk-needs-table-final.js?v=8').length-1!==1)throw new Error('Referensi table final v8 harus tepat satu kali.');
await fs.writeFile(outputPath,html);
console.log(JSON.stringify({gtkNeedsGapData:true,version:6,dinasSource:'VERIFIED-only',reviewRenderer:7,finalTableRenderer:8,gapDataColumn:true,reviewFromWorkflow:true}));
