import fs from 'node:fs/promises';
import path from 'node:path';

const outputPath='.vercel/output/static/index.html';
const staticDir='.vercel/output/static';
const file='gtk-needs-gap-data.js';
const code=await fs.readFile(new URL(`./${file}`,import.meta.url),'utf8');
if(!/SIMANTAB_GTK_NEEDS_GAP_DATA_V9/.test(code))throw new Error('GTK needs unified renderer v9 tidak valid.');
await fs.writeFile(path.join(staticDir,file),code);
let html=await fs.readFile(outputPath,'utf8');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/gtk-needs-gap-data\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/gtk-needs-review-v7\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/gtk-needs-table-final\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
const close=html.lastIndexOf('</body>');
if(close<0)throw new Error('Tag </body> tidak ditemukan saat inject GTK needs v9.');
const tag='<script type="module" src="./gtk-needs-gap-data.js?v=9"></script>\n';
html=html.slice(0,close)+tag+html.slice(close);
if(html.split('./gtk-needs-gap-data.js?v=9').length-1!==1)throw new Error('Referensi GTK needs v9 harus tepat satu kali.');
if(html.includes('./gtk-needs-review-v7.js'))throw new Error('Renderer review v7 lama masih terpasang.');
if(html.includes('./gtk-needs-table-final.js'))throw new Error('Renderer table v8 lama masih terpasang.');
await fs.writeFile(outputPath,html);
console.log(JSON.stringify({gtkNeedsGapData:true,version:9,unifiedRenderer:true,dinasSource:'VERIFIED-only',gapDataColumn:true,reviewFromWorkflow:true,legacyReviewRenderersRemoved:true}));
