import fs from 'node:fs/promises';
import path from 'node:path';
// Inject after legacy service setup; isolated opt-in module, no changes to old E_JABFUNG.
const file='jf-guru-2026.js';
const dir='.vercel/output/static';
const source=await fs.readFile(new URL('./'+file,import.meta.url),'utf8');
if(!source.includes('SIMANTAB_JF_GURU_SURAT_0294_2026_V1'))throw new Error('Modul JF Guru 2026 tidak ditemukan');
await fs.writeFile(path.join(dir,file),source);
const qualFile='jf-qualification-2030.js';
const qualSource=await fs.readFile(new URL('./'+qualFile,import.meta.url),'utf8');
if(!qualSource.includes('SIMANTAB_JF2030_QUALIFICATION_V1'))throw new Error('Modul pemantauan S1/DIV belum tersedia');
await fs.writeFile(path.join(dir,qualFile),qualSource);
const smartFile='smartgtk-unified.js';
const smartSource=await fs.readFile(new URL('./'+smartFile,import.meta.url),'utf8');
if(!smartSource.includes('SIMANTAB_SMARTGTK_UNIFIED_INTAKE_V1'))throw new Error('SMART-GTK unified module missing');
await fs.writeFile(path.join(dir,smartFile),smartSource);
const onboardingFile='smartgtk-onboarding.js';
const onboardingSource=await fs.readFile(new URL('./'+onboardingFile,import.meta.url),'utf8');
if(!onboardingSource.includes('SMARTGTK_MASS_ONBOARDING_V1'))throw new Error('GTK onboarding missing');
await fs.writeFile(path.join(dir,onboardingFile),onboardingSource);
const output=path.join(dir,'index.html');
let html=await fs.readFile(output,'utf8');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/jf-guru-2026\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
if(!html.includes('</body>'))throw new Error('Body SIMANTAB tidak ditemukan');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/jf-qualification-2030\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace(/\s*<script\s+type="module"\s+src="\.\/smartgtk-unified\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace(/\s*<script\s+src="\.\/smartgtk-onboarding\.js\?v=\d+"\s*><\/script>\s*/g,'\n');
html=html.replace('</body>','<script type="module" src="./jf-guru-2026.js?v=2"></script>\n<script type="module" src="./jf-qualification-2030.js?v=5"></script>\n<script type="module" src="./smartgtk-unified.js?v=9"></script>\n<script src="./smartgtk-onboarding.js?v=1"></script>\n</body>');
if((html.match(/jf-guru-2026\.js\?v=2/g)||[]).length!==1)throw new Error('Duplikasi modul JF Guru 2026');
if((html.match(/jf-qualification-2030\.js\?v=5/g)||[]).length!==1)throw new Error('Duplikasi modul pendidikan 2030');
if((html.match(/smartgtk-unified\.js\?v=9/g)||[]).length!==1)throw new Error('SMART-GTK must load once');
if((html.match(/smartgtk-onboarding\.js\?v=1/g)||[]).length!==1)throw new Error('GTK onboarding must load once');
await fs.writeFile(output,html);
console.log(JSON.stringify({jfGuru2026Injected:true,version:1,legacyEJabfungUntouched:true,backendMigrationRequired:true,productionUntouched:true}));
